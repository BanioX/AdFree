import { createRequire } from 'node:module';
import { mkdirSync } from 'node:fs';
import assert from 'node:assert/strict';
const { chromium } = createRequire('/tmp/pw/node_modules/playwright-core/index.js')('playwright-core');
const BASE = process.env.BASE || 'http://127.0.0.1:8765/bruecken/';
const OUT = new URL('./out/', import.meta.url).pathname;
mkdirSync(OUT, { recursive: true });
const errors = [];
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox', '--disable-dev-shm-usage'] });
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
await page.addInitScript(() => {
  localStorage.setItem('spielpause.tutorial.bruecken', 'true');
  if (!localStorage.getItem('spielpause.lang')) localStorage.setItem('spielpause.lang', '"de"');
});
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (m) => { if (m.type() === 'error' && !/Failed to load resource/.test(m.text())) errors.push(m.text()); });
await page.goto(BASE);
await page.locator('.gm-primary').tap();
await page.waitForSelector('.pz button.isle');
await page.screenshot({ path: OUT + '01.png' });
const pair = await page.evaluate(() => window.__sp.pair());
await page.locator('.pz button[data-i="' + pair.a + '"]').tap();
await page.locator('.pz button[data-i="' + pair.b + '"]').tap();
await page.waitForFunction((p) => (window.__sp.state().built[p.a + ',' + p.b] || 0) >= 1, pair);
await page.waitForTimeout(650);
await page.locator('.pz button[data-i="' + pair.a + '"]').evaluate((el) => el.click());
await page.locator('.pz button[data-i="' + pair.b + '"]').evaluate((el) => el.click());
await page.waitForFunction((p) => window.__sp.state().built[p.a + ',' + p.b] !== 1, pair);
await page.evaluate(() => localStorage.setItem('spielpause.lang', '"en"'));
await page.goto(BASE);
await page.evaluate(() => localStorage.removeItem('spielpause.bruecken.match'));
await page.reload();
await page.locator('.gm-primary').tap();
assert.match(await page.locator('.bd-title b').innerText(), /Bridges/);
const fit = await page.evaluate(() => document.documentElement.scrollHeight <= window.innerHeight + 1);
assert.equal(fit, true);
assert.deepEqual(errors, []);
await browser.close();
console.log('bruecken e2e ok');
