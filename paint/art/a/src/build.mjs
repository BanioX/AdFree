// Build all Team-A pictures: node paint/art/a/src/build.mjs [name ...]
// Each src/<name>.mjs exports `meta` ({ id, title, category }) and `build()` -> Pic.
// Writes ../<name>.js (export default Puzzle) and ../index.js (picture list, simple -> rich).

import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { save } from './lib.mjs';
import { autoSplit } from './raster.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const outDir = join(here, '..');

// Order = difficulty (simpler first, richer later).
export const ORDER = [
  'rose',
  'tulpenfeld',
  'schmetterling',
  'seerose',
  'sonnenblumen',
  'igel',
  'fuchs',
  'koi',
  'katze',
  'eule',
  'kolibri',
];

const only = process.argv.slice(2);
const metas = [];
for (const name of ORDER) {
  let mod;
  try {
    mod = await import(pathToFileURL(join(here, `${name}.mjs`)).href);
  } catch (e) {
    if (e.code === 'ERR_MODULE_NOT_FOUND' && e.message.includes(`${name}.mjs`)) continue; // not written yet
    throw e;
  }
  metas.push({ name, ...mod.meta });
  if (only.length && !only.includes(name) && !only.includes(mod.meta.id)) continue;
  const t0 = Date.now();
  const pz = process.env.NOSPLIT ? mod.build().build() : autoSplit(mod.build().build());
  save(pz, join(outDir, `${name}.js`));
  console.log(`${name}.js  ${pz.shapes.length} regions, ${pz.palette.length} colors  (${Date.now() - t0} ms)`);
}

const idx = [
  '// Farbenzauber – Art Team A picture list (simple -> rich). Generated by src/build.mjs.',
  'export const pictures = [',
  ...metas.map(
    (m) =>
      `  { id: ${JSON.stringify(m.id)}, title: ${JSON.stringify(m.title)}, category: ${JSON.stringify(m.category)}, load: () => import('./${m.name}.js').then((m) => m.default) },`,
  ),
  '];',
  '',
];
writeFileSync(join(outDir, 'index.js'), idx.join('\n'));
