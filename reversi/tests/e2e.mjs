import { createRequire } from 'node:module';
import { mkdirSync } from 'node:fs';
import assert from 'node:assert/strict';
const { chromium } = createRequire('/tmp/pw/node_modules/playwright-core/index.js')('playwright-core');
const BASE = process.env.BASE || 'http://127.0.0.1:8765/reversi/';
const OUT = new URL('./out/', import.meta.url).pathname;
mkdirSync(OUT, { recursive: true });
const errors = [];
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox', '--disable-dev-shm-usage'] });
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1, isMobile: true, hasTouch: true });
await page.addInitScript(() => {
  localStorage.setItem('spielpause.tutorial.reversi', 'true');
  localStorage.setItem('spielpause.lang', '"de"');
});
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (m) => { if (m.type() === 'error' && !/Failed to load resource/.test(m.text())) errors.push(m.text()); });
await page.goto(BASE);
await page.waitForSelector('.gm-primary');
await page.screenshot({ path: OUT + '01-menu.png' });
await page.locator('.gm-primary').tap();
await page.waitForSelector('.rv-dot');
await page.screenshot({ path: OUT + '02-board.png' });
const dot = page.locator('.rv-dot').first();
const box = await dot.boundingBox();
await page.touchscreen.tap(box.x + box.width / 2, box.y + box.height / 2);
await page.waitForFunction(() => window.__sp && !window.__sp.busy() && window.__sp.state().turn === 1 && window.__sp.state().cells.filter((c) => c).length > 4, null, { timeout: 8000 });
await page.screenshot({ path: OUT + '03-played.png' });
const fit = await page.evaluate(() => {
  const b = document.querySelector('.rv').getBoundingClientRect();
  const t = document.querySelector('.bd-tools').getBoundingClientRect();
  return b.bottom <= t.top + 2 && t.bottom <= innerHeight + 1;
});
assert.equal(fit, true);
await page.waitForTimeout(550);
const clickOnly = await page.evaluate(() => {
  const n = window.__sp.state().cells.filter(Boolean).length;
  const el = document.querySelector('.rv-dot')?.closest('.rv-cell');
  if (!el) return { ok: false, n };
  el.dispatchEvent(new MouseEvent('click', { bubbles: true, cancelable: true }));
  return { ok: window.__sp.state().cells.filter(Boolean).length > n, n };
});
assert.equal(clickOnly.ok, true, 'Klick ohne pointerup setzt einen Stein');
assert.deepEqual(errors, []);
await browser.close();
console.log('reversi e2e ok');
