import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
const { chromium } = createRequire('/tmp/pw/node_modules/playwright-core/index.js')('playwright-core');
const BASE = process.env.BASE || 'http://127.0.0.1:8765/rundweg/';
const errors = [];
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox', '--disable-dev-shm-usage'] });
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
await page.addInitScript(() => {
  localStorage.setItem('spielpause.tutorial.rundweg', 'true');
  if (!localStorage.getItem('spielpause.lang')) localStorage.setItem('spielpause.lang', '"de"');
});
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (m) => { if (m.type() === 'error' && !/Failed to load resource/.test(m.text())) errors.push(m.text()); });

await page.goto(BASE);
await page.locator('.gm-primary').tap();
await page.waitForSelector('.pz button.edge');
const edges = await page.evaluate(() => [...document.querySelectorAll('.pz button.edge')].slice(0, 2).map((el) => +el.dataset.i));
assert.equal(edges.length, 2);
const onBefore = await page.evaluate(() => window.__sp.state().on.reduce((n, v) => n + v, 0));
await page.locator('.pz button[data-i="' + edges[0] + '"]').tap();
await page.waitForFunction((n) => window.__sp.state().on.reduce((a, v) => a + v, 0) !== n, onBefore);
await page.waitForTimeout(650);
await page.locator('.pz button[data-i="' + edges[1] + '"]').evaluate((el) => el.click());
await page.waitForFunction((n) => window.__sp.state().on.reduce((a, v) => a + v, 0) !== n, onBefore);
await page.evaluate(() => localStorage.setItem('spielpause.lang', '"en"'));
await page.goto(BASE);
await page.evaluate(() => localStorage.removeItem('spielpause.rundweg.match'));
await page.reload();
await page.locator('.gm-primary').tap();
assert.match(await page.locator('.bd-title b').innerText(), /Loop/);
const fit = await page.evaluate(() => document.documentElement.scrollHeight <= window.innerHeight + 1);
assert.equal(fit, true);
assert.deepEqual(errors, []);
await browser.close();
console.log('rundweg e2e ok');
