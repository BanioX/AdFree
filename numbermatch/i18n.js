/** Langer Ziel-Text eines Levels, z.B. «Sammle 3 Sterne». */
export function goalLong(goal) {
  const table = GOAL_TEXT[lang] || GOAL_TEXT.de;
  const g = table[goal.type] || GOAL_TEXT.de[goal.type];
  return fmt(g.long, { n: goal.n });
}
