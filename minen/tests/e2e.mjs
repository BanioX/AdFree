import { createRequire } from 'node:module';
import { mkdirSync } from 'node:fs';
import assert from 'node:assert/strict';
const { chromium } = createRequire('/tmp/pw/node_modules/playwright-core/index.js')('playwright-core');
const BASE = process.env.BASE || 'http://127.0.0.1:8765/minen/';
const OUT = new URL('./out/', import.meta.url).pathname;
mkdirSync(OUT, { recursive: true });
const errors = [];
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox', '--disable-dev-shm-usage'] });
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
await page.addInitScript(() => {
  localStorage.setItem('spielpause.tutorial.minen', 'true');
  if (!localStorage.getItem('spielpause.lang')) localStorage.setItem('spielpause.lang', '"de"');
});
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (m) => { if (m.type() === 'error' && !/Failed to load resource/.test(m.text())) errors.push(m.text()); });
await page.goto(BASE);
await page.locator('.gm-primary').tap();
await page.waitForSelector('.pz button');
await page.screenshot({ path: OUT + '01.png' });
await page.locator('.pz button[data-i="0"]').tap();
await page.waitForFunction(() => window.__sp.state().open[0]);
const over = await page.evaluate(() => window.__sp.state().boom || window.__sp.state().open.every((v, i) => v || window.__sp.state().mine[i]));
if (!over) {
  await page.waitForTimeout(650);
  const closed = await page.evaluate(() => window.__sp.state().open.findIndex((v) => !v));
  await page.locator('.pz button[data-i="' + closed + '"]').evaluate((el) => el.click());
  await page.waitForFunction((i) => window.__sp.state().open[i] || window.__sp.state().flag[i], closed);
}
await page.evaluate(() => localStorage.setItem('spielpause.lang', '"en"'));
await page.goto(BASE);
await page.evaluate(() => localStorage.removeItem('spielpause.minen.match'));
await page.reload();
await page.locator('.gm-primary').tap();
assert.match(await page.locator('.bd-title b').innerText(), /Minesweeper/);
const fit = await page.evaluate(() => document.documentElement.scrollHeight <= window.innerHeight + 1);
assert.equal(fit, true);
assert.deepEqual(errors, []);
await browser.close();
console.log('minen e2e ok');
