import { createRequire } from 'node:module';
import { mkdirSync } from 'node:fs';
import assert from 'node:assert/strict';
const { chromium } = createRequire('/tmp/pw/node_modules/playwright-core/index.js')('playwright-core');
const BASE = process.env.BASE || 'http://127.0.0.1:8765/kreuzwort/';
const OUT = new URL('./out/', import.meta.url).pathname;
mkdirSync(OUT, { recursive: true });
const errors = [];
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox', '--disable-dev-shm-usage'] });
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
await page.addInitScript(() => {
  localStorage.setItem('spielpause.tutorial.kreuzwort', 'true');
  if (!localStorage.getItem('spielpause.lang')) localStorage.setItem('spielpause.lang', '"de"');
});
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (m) => { if (m.type() === 'error' && !/Failed to load resource/.test(m.text())) errors.push(m.text()); });
await page.goto(BASE);
await page.locator('.gm-primary').tap();
await page.waitForSelector('.xw-grid');
await page.screenshot({ path: OUT + '01.png' });
const open = await page.evaluate(() => {
  const s = window.__sp.state();
  const cells = [];
  s.mask.forEach((row, r) => [...row].forEach((ch, c) => { if (ch !== '#') cells.push({ r, c, ch }); }));
  return cells;
});
await page.locator('[data-cell="' + open[0].r + ',' + open[0].c + '"]').tap();
await page.locator('.xw-keys [data-ch="' + open[0].ch + '"]').tap();
await page.waitForFunction((cell) => window.__sp.state().fill[cell.r + ',' + cell.c] === cell.ch, open[0]);
await page.waitForTimeout(650);
await page.locator('[data-cell="' + open[1].r + ',' + open[1].c + '"]').evaluate((el) => el.click());
await page.locator('.xw-keys [data-ch="' + open[1].ch + '"]').evaluate((el) => el.click());
await page.waitForFunction((cell) => window.__sp.state().fill[cell.r + ',' + cell.c] === cell.ch, open[1]);
await page.evaluate(() => localStorage.setItem('spielpause.lang', '"en"'));
await page.goto(BASE);
await page.evaluate(() => localStorage.removeItem('spielpause.kreuzwort.match'));
await page.reload();
await page.locator('.gm-primary').tap();
assert.match(await page.locator('.bd-title b').innerText(), /Mini Crossword/);
const clue = await page.locator('.xw-clues').innerText();
assert.match(clue, /Across|Down/);
const fit = await page.evaluate(() => document.documentElement.scrollHeight <= window.innerHeight + 1);
assert.equal(fit, true);
assert.deepEqual(errors, []);
await browser.close();
console.log('kreuzwort e2e ok');
